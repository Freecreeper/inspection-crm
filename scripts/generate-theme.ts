// Generates src/app/theme.css and src/lib/theme/palettes.generated.ts — the
// app's whole color system. Run `npx tsx scripts/generate-theme.ts` after
// changing a palette below, and commit both outputs.
//
// Components use semantic tokens (bg-primary, text-muted-foreground,
// bg-sidebar-active, bg-danger-soft, border-input, outline-ring, …), defined
// for every palette in light and dark by src/lib/theme/roles.ts, which picks
// shades by measured contrast. The neutral-* and accent-* scales stay
// available for in-between shades. Status colors (success green, warning
// amber, danger red, info blue) are the same in every palette; only the mode
// changes them. Tailwind's other color families get dark-mode values too, so
// leftover uses (calendar categories) still read in dark mode.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { STOPS, formatOklch, type Stop } from "../src/lib/theme/color";
import { DARK, SYSTEM, declarations, paletteCss, paletteTokens } from "../src/lib/theme/css";
import { PALETTES, STATUS, raw } from "../src/lib/theme/presets";

const root = path.join(__dirname, "..");
const CHROMATIC = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"];

const mirror = (s: Stop): Stop => (s === 50 ? 950 : s === 950 ? 50 : ((1000 - s) as Stop));
const darkChromatic = Object.fromEntries(CHROMATIC.flatMap((f) => STOPS.map((s) => [`${f}-${s}`, raw[f][mirror(s)]])));

const forest = PALETTES.forest;
const css = [
  "/* GENERATED by scripts/generate-theme.ts; edit that, then run it. */",
  // Defaults (Forest, light) in @theme so Tailwind generates the utilities.
  `@theme {\n${declarations(paletteTokens(forest, "light", STATUS))}\n}`,
  // Other color families in dark mode (whatever the palette).
  `${DARK} {\n  color-scheme: dark;\n${declarations(darkChromatic)}\n}`,
  `@media (prefers-color-scheme: dark) {\n  ${SYSTEM} {\n    color-scheme: dark;\n${declarations(darkChromatic, "    ")}\n  }\n}`,
  paletteCss(":root", forest, STATUS, { light: false }),
  ...Object.entries(PALETTES)
    .filter(([id]) => id !== "forest")
    .map(([id, p]) => paletteCss(`:root[data-palette="${id}"]`, p, p.highContrast ? STATUS : undefined)),
  "",
].join("\n");
writeFileSync(path.join(root, "src/app/theme.css"), css);

// Palette list for the Appearance picker, with swatches from its own colors.
const swatches = Object.entries(PALETTES).map(([id, p]) => {
  const t = paletteTokens(p, "light");
  return { id, label: p.label, sidebar: p.sidebar, swatch: { accent: formatOklch(t.accent), tint: formatOklch(t.selected), primary: formatOklch(t.primary), sidebar: formatOklch(t.sidebar) } };
});
writeFileSync(
  path.join(root, "src/lib/theme/palettes.generated.ts"),
  `// GENERATED by scripts/generate-theme.ts; edit that, then run it.\n\nexport const PALETTES = ${JSON.stringify(swatches, null, 2)} as const;\n`
);
console.log(`Wrote src/app/theme.css (${css.length} bytes) and palettes.generated.ts (${swatches.length} palettes)`);
